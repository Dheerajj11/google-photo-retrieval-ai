import fs from 'node:fs'
import path from 'node:path'

const root = process.cwd()
const photosDir = path.join(root, 'public', 'photos')
const outFile = path.join(root, 'src', 'data', 'generatedPhotos.js')
const supported = new Set(['.jpg','.jpeg','.png','.webp','.avif'])

fs.mkdirSync(photosDir, { recursive:true })
fs.mkdirSync(path.dirname(outFile), { recursive:true })

const files = fs.readdirSync(photosDir, { withFileTypes:true })
  .filter(x => x.isFile() && supported.has(path.extname(x.name).toLowerCase()))
  .map(x => x.name)
  .sort((a,b)=>a.localeCompare(b, undefined, {numeric:true,sensitivity:'base'}))

const humanize = (name) => name
  .replace(/\.[^.]+$/, '')
  .replace(/[_-]+/g, ' ')
  .replace(/\s+/g, ' ')
  .trim()

const photos = files.map((file,i) => ({
  id: `project-${String(i+1).padStart(3,'0')}`,
  url: `/photos/${encodeURIComponent(file).replace(/%2F/g,'/')}`,
  title: humanize(file) || `Project photo ${i+1}`,
  taken: null,
  place: '',
  cluster: 'project',
  tags: [],
  description: 'Photo from the curated graduation-project demo library.',
  source: 'project-library'
}))

const source = `// AUTO-GENERATED by scripts/generate-manifest.mjs
// Add/remove files in public/photos/ and rebuild. Do not edit this file manually.
export const generatedPhotos = ${JSON.stringify(photos,null,2)}
`

fs.writeFileSync(outFile, source)
console.log(`Photo manifest: ${photos.length} image(s) found in public/photos/`)
